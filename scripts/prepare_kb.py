def ordered_map() -> list[tuple[str, str]]:
    pairs = sorted(MAP.items(), key=lambda kv: len(kv[0]), reverse=True)
    for shorter, _ in pairs:
        for longer, _ in pairs:
            if longer != shorter and len(longer) == len(shorter) and longer.startswith(shorter):
                raise SystemExit(f"равная длина и префикс: {shorter!r} / {longer!r}")
    return pairs


def apply_map(text: str, pairs: list[tuple[str, str]]) -> str:
    for src, dst in pairs:
        text = text.replace(src, dst)
    return text


def slug(text: str, fallback: str) -> str:
    title = text.splitlines()[0].lstrip("# ").strip()
    name = re.sub(r"[^\w\-]+", "_", title, flags=re.UNICODE).strip("_").lower()
    return name or fallback


def main() -> None:
    pairs = ordered_map()
    KB.mkdir(parents=True, exist_ok=True)
    for old in KB.glob("*"):
        if old.suffix.lower() in {".md", ".txt"} and old.name != "README.md":
            old.unlink()

    leaks: list[str] = []
    written: list[str] = []
    for fallback, raw in DOCS.items():
        text = apply_map(raw.strip() + "\n", pairs)
        name = slug(text, Path(fallback).stem) + ".md"
        (KB / name).write_text(text, encoding="utf-8")
        written.append(name)
        found = [w for w in FORBIDDEN if w in text]
        if found:
            leaks.append(f"{name}: {found}")

    payload = {"_meta": META, "map": dict(pairs)}
